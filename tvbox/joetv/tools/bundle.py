#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""把 Worker 与生成目录打包成单文件，便于 Cloudflare Dashboard 直接粘贴。"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parent


def main() -> int:
    source = (PROJECT / "src/index.js").read_text(encoding="utf-8")
    catalog_text = (PROJECT / "data/catalog.js").read_text(encoding="utf-8").strip()
    marker = "export const CATALOG = "
    if not catalog_text.startswith("//"):
        raise SystemExit("catalog.js 格式异常")
    catalog_text = catalog_text[catalog_text.index(marker) + len(marker):].rstrip(";")
    catalog = json.loads(catalog_text)
    inline = "const CATALOG = " + json.dumps(catalog, ensure_ascii=False, separators=(",", ":")) + ";"
    import_line = 'import { CATALOG } from "../data/catalog.js";'
    if import_line not in source:
        raise SystemExit("找不到 catalog import")
    source = source.replace(import_line, inline, 1)
    source = source.replace("export const __test__", "const __test__", 1)
    header = (
        "// JoeTV Worker bundle. Generated by tools/bundle.py.\n"
        "// Sources: %d; generated_at: %s\n"
        % (catalog.get("source_count"), catalog.get("generated_at"))
    )
    out = header + source
    dist = PROJECT / "dist"
    dist.mkdir(exist_ok=True)
    path = dist / "worker.js"
    path.write_text(out, encoding="utf-8", newline="\n")
    # Cloudflare Pages advanced mode entry
    (dist / "_worker.js").write_text(out, encoding="utf-8", newline="\n")
    digest = hashlib.sha256(out.encode("utf-8")).hexdigest()
    print("wrote %s bytes=%d sha256=%s" % (path, len(out.encode("utf-8")), digest))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
